"""Vendor workflow contracts into standalone service build contexts.

Run after editing workflow-service/app/contracts. CI uses --check to reject drift.
This avoids runtime dependencies between service containers or Docker context changes.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "service/workflow-service/app/contracts"
TARGET = ROOT / "service/execution-service/app/contracts"
HEADER = "# Generated by scripts/sync_workflow_contracts.py; edit workflow-service/app/contracts.\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for source in sorted(SOURCE.glob("*.py")):
        target = TARGET / source.name
        expected = HEADER + source.read_text()
        if target.exists() and target.read_text() == expected:
            continue
        if args.check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)
    if stale:
        parser.exit(
            1,
            "Outdated workflow contracts; run scripts/sync_workflow_contracts.py:\n"
            + "\n".join(stale)
            + "\n",
        )


if __name__ == "__main__":
    main()
