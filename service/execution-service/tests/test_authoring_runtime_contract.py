def test_bundled_contracts_match_authoritative_source():
    root = Path(__file__).resolve().parents[3]
    source = root / "service/workflow-service/app/contracts"
    target = root / "service/execution-service/app/contracts"
    header = (
        "# Generated by scripts/sync_workflow_contracts.py; edit workflow-service/app/contracts.\n"
    )
    for item in source.glob("*.py"):
        assert (target / item.name).read_text() == header + item.read_text()


@pytest.mark.parametrize(
    "prompt",
    ["Report on {{trigger_1.research_topic}}", "{{trigger.data.missing}}", "prefix {{broken"],
)
def test_resolver_reports_field_without_prompt_or_payload(prompt):
    resolver = ExpressionResolver(ExecutionContext({"research_topic": "private-payload"}))
    with pytest.raises(ExpressionResolutionError) as caught:
        resolver.resolve({"nested": [{"prompt": prompt}]}, strict=True)
    error = classify_error(caught.value, "generate_1", "ai.generate")
    assert error["code"] == "UNRESOLVED_EXPRESSION"
    assert error["field"] == "nested[0].prompt"
    assert error["retryable"] is False
    assert "private-payload" not in json.dumps(error) and "Report on" not in json.dumps(error)


def test_correct_expression_preserves_whole_types_and_json_closing_braces():
    resolver = ExpressionResolver(ExecutionContext({"research_topic": "How RAG works", "count": 3}))
    assert resolver.resolve(
        {
            "prompt": "Report on {{trigger.data.research_topic}}",
            "count": "{{trigger.data.count}}",
            "json": '{"nested": {"value": 1}}',
        },
        strict=True,
    ) == {"prompt": "Report on How RAG works", "count": 3, "json": '{"nested": {"value": 1}}'}


@pytest.mark.parametrize(
    "patch,field",
    [
        ({"model": "x" * 151}, "model"),
        ({"prompt": "x" * 10001}, "prompt"),
        ({"instructions": "x" * 10001}, "instructions"),
        ({"rag_context": "x" * 2001}, "rag_context"),
        ({"input_mappings": {}}, "input_mappings"),
        ({"output_format": "json"}, "output_format"),
        ({"provider": "openai"}, "provider"),
    ],
)
def test_runtime_enforces_authoring_limits_and_unknown_fields_before_credentials(
    monkeypatch, patch, field
):
    factory = Mock(side_effect=AssertionError("Provider lookup must not run"))
    monkeypatch.setattr(ai_generate, "AIProviderConnectionService", factory)
    with pytest.raises(NodeConfigurationError) as caught:
        asyncio.run(ai_generate.execute_ai_generate({**BASE, **patch}, WORKSPACE, AsyncMock()))
    error = classify_error(caught.value, "generate_1", "ai.generate")
    assert error["code"] == "AI_INVALID_CONFIGURATION" and error["field"] == field
    assert error["validation_type"] and error["retryable"] is False
    assert "x" * 151 not in json.dumps(error)
    factory.assert_not_called()


def test_connection_expressions_are_deferred_only_during_authoring(monkeypatch):
    configuration = {**BASE, "connection_id": "{{trigger.data.connection_id}}"}
    assert (
        AIGenerateConfig.model_validate(configuration).connection_id
        == configuration["connection_id"]
    )
    credentials, _ = setup_handler(monkeypatch)
    with pytest.raises(NodeConfigurationError):
        asyncio.run(ai_generate.execute_ai_generate(configuration, WORKSPACE, AsyncMock()))
    credentials.assert_not_awaited()


def test_corrected_incident_configuration_executes_with_mocked_provider(monkeypatch):
    credentials, generate = setup_handler(monkeypatch)
    resolver = ExpressionResolver(ExecutionContext({"research_topic": "How RAG works"}))
    configuration = resolver.resolve(
        {**BASE, "prompt": "Report on {{trigger.data.research_topic}}"}, strict=True
    )
    result = asyncio.run(ai_generate.execute_ai_generate(configuration, WORKSPACE, AsyncMock()))
    assert result["content"] == "Summary"
    assert generate.await_args.kwargs["prompt"] == "Report on How RAG works"
    credentials.assert_awaited_once()


def test_runner_rejects_bad_reference_before_dispatch(monkeypatch):
    from app.engine import runner
    from test_execution_components import RUNNER_WORKSPACE_ID, runner_setup

    nodes = [
        {"node_id": "trigger_1", "node_type": "trigger.manual"},
        {
            "node_id": "generate_1",
            "node_type": "ai.generate",
            "configuration": {**BASE, "prompt": "Report on {{trigger_1.research_topic}}"},
        },
    ]
    state = runner_setup(
        monkeypatch, nodes, [{"source_node_id": "trigger_1", "target_node_id": "generate_1"}]
    )
    handler = AsyncMock(side_effect=AssertionError("AI handler must not run"))
    monkeypatch.setattr(runner, "execute_ai_generate", handler)
    with pytest.raises(ExpressionResolutionError):
        asyncio.run(
            runner.run_execution(
                state["execution"].id,
                "w",
                "v",
                RUNNER_WORKSPACE_ID,
                trigger_data={"research_topic": "How RAG works"},
            )
        )
    handler.assert_not_awaited()
    error = state["steps"][-1].error
    assert error["code"] == "UNRESOLVED_EXPRESSION" and error["field"] == "prompt"
    assert error["expression"] == "{{trigger_1.research_topic}}"
